import { getPublicStudentReport } from "../controllers/publicController";
import { Student } from "../models/Student";
import { Teacher } from "../models/Teacher";
import { Group } from "../models/Group";
import { Grade } from "../models/Grade";
import { AttendanceRecord } from "../models/AttendanceRecord";
import { MonthlySubscription } from "../models/MonthlySubscription";
import { ExamGrade } from "../models/Exam";
import { BookSale } from "../models/BookSale";
import { StudentMembership } from "../models/StudentMembership";
import {AttendanceSubstitution} from "../models/AttendanceSubstitution";
import { SystemSettings } from "../models/SystemSettings";
const chain = (data: unknown): any => ({ select() { return this; }, sort() { return this; }, populate() { return this; }, lean() { return this; }, then(resolve: any, reject: any) { return Promise.resolve(data).then(resolve, reject); } });
const response = (): any => ({ statusCode: 200, status(code: number) { this.statusCode = code; return this; }, json: jest.fn() });
beforeEach(()=>{jest.spyOn(AttendanceSubstitution,"find").mockReturnValue(chain([]));});
afterEach(() => jest.restoreAllMocks());
test("monthly report retains previous-group attendance, separates period scores and excludes exempt cash", async () => {
  jest.spyOn(Student, "findById").mockReturnValue(chain({ _id: "student", teacher_id: "teacher", name: "Test Student", group_id: "group", grade_id: "grade" }));
  jest.spyOn(Teacher, "findById").mockReturnValue(chain({ name: "Teacher" }));
  jest.spyOn(Group, "findById").mockReturnValue(chain({ name: "Current" }));
  jest.spyOn(Grade, "findById").mockReturnValue(chain({ name: "Grade" }));
  jest.spyOn(SystemSettings, "findOne").mockReturnValue(chain({}));
  const attendance = jest.spyOn(AttendanceRecord, "find").mockReturnValue(chain([{ session_date: "2026-10-01", status: "present", group_id: { name: "Previous" } }, { session_date: "2026-10-12", status: "absent", group_id: { name: "Current" } }]));
  jest.spyOn(AttendanceRecord, "findOne").mockReturnValue(chain({ session_date: "2026-10-01" }));
  jest.spyOn(MonthlySubscription, "find").mockReturnValue(chain([{ year: 2026, month: 10, status: "exempt", amount: 250, discount: 50 }, { year: 2026, month: 9, status: "due", amount: 200, discount: 20 }, { year: 2026, month: 8, status: "paid", amount: 200, discount: 0 }]));
  const exam = (date: string, score: number, max: number) => ({ score, exam_id: { title: date, exam_date: date, max_score: max } });
  jest.spyOn(ExamGrade, "find").mockReturnValue(chain([exam("2026-10-05", 8, 10), exam("2026-10-12", 10, 20), exam("2026-09-01", 10, 10), exam("2026-11-01", 0, 10)]));
  const books = jest.spyOn(BookSale, "find").mockReturnValue(chain([]));
  jest.spyOn(StudentMembership, "find").mockReturnValue(chain([{ group_id: { _id: "group", name: "Current" }, starts_on: "2026-10-01", ends_on: null }]));
  jest.spyOn(AttendanceRecord, "aggregate").mockResolvedValue([{ _id: { group_id: "group", date: "2026-10-15" } }]);
  const res = response();
  await getPublicStudentReport({ params: { id: "student" }, query: { month: "10", year: "2026" } } as any, res);
  const report = res.json.mock.calls[0][0];
  expect(report).toMatchObject({ attendance_present: 1, attendance_absent: 2, exam_average: 65, exam_average_all_time: 77, payment_status: "exempt", subscription_amount: 200, arrears_count: 1, arrears_amount: 180, last_exam_score: 10 });
  expect(report.attendance).toContainEqual({ date: "2026-10-15", status: "unrecorded", group: "Current" });
  expect(report.exams).toHaveLength(2);
  expect(report.attendance[0].group).toBe("Previous");
  expect(attendance).toHaveBeenCalledWith({ student_id: "student", teacher_id: "teacher", month: 10, year: 2026 });
  expect(books).toHaveBeenCalledWith({ student_id: "student", teacher_id: "teacher", month: 10, year: 2026, status: "active" });
});
test.each([{ month: "13", year: "2026" }, { month: "1", year: "oops" }])("rejects invalid periods before database reads", async query => {
  const find = jest.spyOn(Student, "findById");
  const res = response();
  await getPublicStudentReport({ params: { id: "student" }, query } as any, res);
  expect(res.statusCode).toBe(400); expect(find).not.toHaveBeenCalled();
});
