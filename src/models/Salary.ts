import mongoose, { Schema, Document } from "mongoose";

export interface ISalary extends Document {
  employee_name: string;
  role: string;
  amount: number;
  month: number;
  year: number;
  is_recurring: boolean;
  start_month: number;
  start_year: number;
  end_month?: number | null;
  end_year?: number | null;
  notes?: string;
  payment_status: "paid" | "pending";
  is_virtual_instance: boolean; // true = generated by cron from a recurring template
  template_id?: mongoose.Types.ObjectId;
  teacher_id: mongoose.Types.ObjectId;
  created_at: Date;
}

const SalarySchema = new Schema<ISalary>(
  {
    employee_name: { type: String, required: true, trim: true },
    role: { type: String, required: true, trim: true },
    amount: { type: Number, required: true, min: [0, "المبلغ لا يمكن أن يكون سالباً"], max: [10_000_000, "المبلغ يتجاوز الحد المسموح به"] },
    month: { type: Number, required: true, min: [1, "الشهر يجب أن يكون بين 1 و 12"], max: [12, "الشهر يجب أن يكون بين 1 و 12"] },
    year: { type: Number, required: true, min: [2000, "السنة غير صالحة"], max: [2100, "السنة غير صالحة"] },
    is_recurring: { type: Boolean, default: false },
    start_month: { type: Number, default: null, min: [1, "الشهر يجب أن يكون بين 1 و 12"], max: [12, "الشهر يجب أن يكون بين 1 و 12"] },
    start_year: { type: Number, default: null, min: [2000, "السنة غير صالحة"], max: [2100, "السنة غير صالحة"] },
    end_month: { type: Number, default: null, min: [1, "الشهر يجب أن يكون بين 1 و 12"], max: [12, "الشهر يجب أن يكون بين 1 و 12"] },
    end_year: { type: Number, default: null, min: [2000, "السنة غير صالحة"], max: [2100, "السنة غير صالحة"] },
    notes: { type: String, default: "" },
    payment_status: { type: String, enum: ["paid", "pending"], default: "paid" },
    is_virtual_instance: { type: Boolean, default: false },
    template_id: { type: Schema.Types.ObjectId, ref: "Salary", default: null },
    teacher_id: { type: Schema.Types.ObjectId, ref: "Teacher", required: true },
  },
  {
    timestamps: { createdAt: "created_at", updatedAt: "updated_at" },
    toJSON: {
      virtuals: true,
      transform: (_doc: unknown, ret: Record<string, unknown>) => { delete ret._id; delete ret.__v; return ret; },
    },
  }
);

// Primary lookup: teacher + year + month
SalarySchema.index({ teacher_id: 1, year: 1, month: 1 });
// For recurring salary year-filter query: teacher + is_recurring + start_year + end_year
SalarySchema.index({ teacher_id: 1, is_recurring: 1, start_year: 1 });

SalarySchema.index({ template_id: 1, year: 1, month: 1 }, { unique: true, partialFilterExpression: { template_id: { $type: "objectId" } } });
export const Salary = mongoose.model<ISalary>("Salary", SalarySchema);
